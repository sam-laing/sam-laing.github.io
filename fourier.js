/* Fourier epicycles drawing cartoon characters behind the hero, one after another.
   Data (coefficients + pen lifts) comes from characters.js, generated by trace/trace.py. */
(function () {
  var cv = document.getElementById('bg-canvas');
  var chars = window.FOURIER_CHARACTERS || [];
  if (!cv || !cv.getContext || !chars.length) return;
  var ctx = cv.getContext('2d');
  var reduce = window.matchMedia && matchMedia('(prefers-reduced-motion: reduce)').matches;

  var DRAW_MS = 16000, HOLD_MS = 3000, FADE_MS = 900;
  var SAMPLES = 4000;                     // points on the finished curve
  var N_CIRCLES = 60;                     // only the biggest circles are worth drawing
  var W = 0, H = 0, R = 0;

  /* precompute the finished curve once per character */
  function prepare(c) {
    if (c.ready) return c;
    var n = c.coeffs.length, k = new Float64Array(n), re = new Float64Array(n), im = new Float64Array(n);
    for (var i = 0; i < n; i++) { k[i] = c.coeffs[i][0]; re[i] = c.coeffs[i][1]; im[i] = c.coeffs[i][2]; }
    var xs = new Float32Array(SAMPLES), ys = new Float32Array(SAMPLES), up = new Uint8Array(SAMPLES);
    for (var s = 0; s < SAMPLES; s++) {
      var t = s / SAMPLES, x = 0, y = 0;
      for (var j = 0; j < n; j++) {
        var a = 2 * Math.PI * k[j] * t, ca = Math.cos(a), sa = Math.sin(a);
        x += re[j] * ca - im[j] * sa;
        y += re[j] * sa + im[j] * ca;
      }
      xs[s] = x; ys[s] = y;
    }
    c.pen_up.forEach(function (r) {
      for (var s = Math.floor(r[0] * SAMPLES); s < Math.min(SAMPLES, Math.ceil(r[1] * SAMPLES)); s++) up[s] = 1;
    });
    c.k = k; c.re = re; c.im = im; c.xs = xs; c.ys = ys; c.up = up; c.ready = true;
    return c;
  }

  function resize() {
    var dpr = window.devicePixelRatio || 1, r = cv.getBoundingClientRect();
    W = r.width; H = r.height; R = Math.min(W, H) * 0.44;
    cv.width = Math.round(W * dpr); cv.height = Math.round(H * dpr);
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
  }
  function X(x) { return W / 2 + R * x; }
  function Y(y) { return H / 2 - R * y; }

  function colors() {
    var css = getComputedStyle(document.documentElement);
    return { accent: css.getPropertyValue('--accent').trim(), muted: css.getPropertyValue('--muted').trim(),
             fg: css.getPropertyValue('--fg').trim() };
  }

  function draw(c, p, alpha, machine) {
    var col = colors(), end = Math.floor(p * SAMPLES);
    ctx.clearRect(0, 0, W, H);

    // the ink so far, lifting the pen between strokes
    ctx.globalAlpha = 0.6 * alpha;
    ctx.strokeStyle = col.accent; ctx.lineWidth = 1.6; ctx.lineJoin = ctx.lineCap = 'round';
    ctx.beginPath();
    var down = false;
    for (var s = 0; s < end; s++) {
      if (c.up[s]) { down = false; continue; }
      if (!down) { ctx.moveTo(X(c.xs[s]), Y(c.ys[s])); down = true; }
      else ctx.lineTo(X(c.xs[s]), Y(c.ys[s]));
    }
    ctx.stroke();

    // the epicycles at time p
    if (machine) {
      var t = p, x = 0, y = 0;
      ctx.lineWidth = 1;
      for (var j = 0; j < c.k.length; j++) {
        var a = 2 * Math.PI * c.k[j] * t, ca = Math.cos(a), sa = Math.sin(a);
        var nx = x + c.re[j] * ca - c.im[j] * sa, ny = y + c.re[j] * sa + c.im[j] * ca;
        var r = Math.hypot(c.re[j], c.im[j]) * R;
        if (j > 0 && j <= N_CIRCLES && r > 1.5) {
          ctx.globalAlpha = 0.16 * alpha; ctx.strokeStyle = col.muted;
          ctx.beginPath(); ctx.arc(X(x), Y(y), r, 0, 2 * Math.PI); ctx.stroke();
        }
        if (j > 0 && r > 0.4) {
          ctx.globalAlpha = 0.4 * alpha; ctx.strokeStyle = col.fg;
          ctx.beginPath(); ctx.moveTo(X(x), Y(y)); ctx.lineTo(X(nx), Y(ny)); ctx.stroke();
        }
        x = nx; y = ny;
      }
      ctx.globalAlpha = alpha; ctx.fillStyle = col.accent;
      ctx.beginPath(); ctx.arc(X(x), Y(y), 2.5, 0, 2 * Math.PI); ctx.fill();
    }

    ctx.globalAlpha = 1;
  }

  /* timeline: draw -> hold -> fade -> next character. Time only advances while the canvas is on screen. */
  var idx = 0, elapsed = 0, last = null, visible = true;
  if ('IntersectionObserver' in window) {
    new IntersectionObserver(function (e) { visible = e[0].isIntersecting; }).observe(cv);
  }

  function frame(now) {
    var dt = last === null ? 0 : Math.min(100, now - last);
    last = now;
    if (visible) {
      elapsed += dt;
      var c = prepare(chars[idx]);
      if (elapsed < DRAW_MS) draw(c, elapsed / DRAW_MS, 1, true);
      else if (elapsed < DRAW_MS + HOLD_MS) draw(c, 1, 1, false);
      else if (elapsed < DRAW_MS + HOLD_MS + FADE_MS) draw(c, 1, 1 - (elapsed - DRAW_MS - HOLD_MS) / FADE_MS, false);
      else { idx = (idx + 1) % chars.length; elapsed = 0; }
    }
    requestAnimationFrame(frame);
  }

  /* reduced motion: finished drawings only, swapped every few seconds */
  function still() {
    draw(prepare(chars[idx]), 1, 1, false);
  }

  resize();
  var onResize = function () { resize(); if (reduce) still(); };
  if ('ResizeObserver' in window) new ResizeObserver(onResize).observe(cv);   // the figure changes size with the layout
  else window.addEventListener('resize', onResize);
  if (reduce) {
    still();
    setInterval(function () { idx = (idx + 1) % chars.length; still(); }, 8000);
    new MutationObserver(still).observe(document.documentElement, { attributes: true, attributeFilter: ['data-theme'] });
  } else {
    requestAnimationFrame(frame);
  }
})();
